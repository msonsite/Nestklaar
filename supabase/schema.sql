-- ─── Opruimen van een eerdere versie ────────────────────────────────────────
drop table if exists public.items cascade;
drop table if exists public.list_members cascade;
drop table if exists public.lists cascade;
drop function if exists public.create_list(text);
drop function if exists public.join_list(text);
drop function if exists public.is_member(uuid);
drop function if exists public.touch_item();

-- ─── Tabel ──────────────────────────────────────────────────────────────────
create table public.items (
  id          uuid primary key default gen_random_uuid(),
  category    text not null check (length(category) between 1 and 120),
  name        text not null check (length(name) between 1 and 120),
  priority    text not null default 'A' check (priority in ('E','A','X')),
  done        boolean not null default false,
  price       numeric(10,2) check (price is null or (price >= 0 and price < 1000000)),
  is_custom   boolean not null default false,
  sort        integer not null default 0,
  updated_at  timestamptz not null default now(),
  created_at  timestamptz not null default now()
);
create index items_sort_idx on public.items(sort);

create function public.touch_item() returns trigger
language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end $$;
create trigger items_touch before update on public.items
for each row execute function public.touch_item();

-- ─── Toegang: iedereen met de app mag lezen en bewerken ─────────────────────
alter table public.items enable row level security;

create policy "iedereen leest"      on public.items for select to anon, authenticated using (true);
create policy "iedereen voegt toe"  on public.items for insert to anon, authenticated with check (true);
create policy "iedereen wijzigt"    on public.items for update to anon, authenticated using (true) with check (true);
-- Enkel zelf toegevoegde items kunnen verwijderd worden, de standaardlijst blijft staan
create policy "eigen items wissen"  on public.items for delete to anon, authenticated using (is_custom);

grant select, insert, update, delete on public.items to anon, authenticated;

-- ─── Live updates tussen toestellen ─────────────────────────────────────────
do $$
begin
  alter publication supabase_realtime add table public.items;
exception when duplicate_object then null;
end $$;

